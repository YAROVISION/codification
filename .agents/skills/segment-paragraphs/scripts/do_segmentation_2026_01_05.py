def main():
    if not SRC_PATH.exists():
        print(f"Помилка: файл {SRC_PATH} не знайдено.")
        sys.exit(1)

    with open(SRC_PATH, 'r', encoding='utf-8', errors='surrogateescape', newline='') as f:
        orig_text = f.read()

    # Очищення номерів сторінок та колонтитулів
    cleaned = re.sub(r'\n\s*\d{1,2}\s*\n\s*(?:ляд суд )?Огляд судової практики ККС ВС\s*\n', '\n', orig_text)

    url_pat = re.compile(
        r'(?:<https://reyestr\.court\.gov\.ua/Review/\d+>|https://reyestr\.court\.gov\.ua/Review/\d+|https://reyestr\.court\.gov\.ua/review/\d+)',
        re.IGNORECASE
    )

    output_parts = []

    # 1. PREAMBLE
    output_parts.append(
        "<!-- === SEGMENT: PREAMBLE | Огляд судової практики ККС ВС щодо затримання особи. ЗМІСТ. Перелік скорочень. Технічний сегмент. Не підлягає розподілу === -->\n\n"
        + PREAMBLE_TEXT
    )

    # 2. Судові рішення
    curr_pos = 0
    for idx, (sub, sec_title, prefix) in enumerate(SUBCASES, 1):
        m_sub = re.search(r'\n\s*' + re.escape(sub) + r'\.\s+', cleaned[curr_pos:])
        if not m_sub:
            raise ValueError(f"Не знайдено підрозділ {sub} після позиції {curr_pos}")
        start = curr_pos + m_sub.start()
        m_url = url_pat.search(cleaned[start:])
        if not m_url:
            raise ValueError(f"Не знайдено посилання ЄДРСР для підрозділу {sub}")
        end = start + m_url.end()
        curr_pos = end

        raw_block = cleaned[start:end].strip()
        stripped = re.sub(r'^\s*' + re.escape(sub) + r'\.\s*', '', raw_block)
        lines = [l.strip() for l in stripped.split('\n') if l.strip()]
        one_line = ' '.join(lines)
        one_line = re.sub(r'[ \t]+', ' ', one_line).strip()

        # Приведення URL до єдиного формату <https://reyestr.court.gov.ua/Review/...>
        one_line = re.sub(r'<https://reyestr\.court\.gov\.ua/[Rr]eview/(\d+)>', r'https://reyestr.court.gov.ua/Review/\1', one_line)
        one_line = re.sub(r'https://reyestr\.court\.gov\.ua/[Rr]eview/(\d+)', r'<https://reyestr.court.gov.ua/Review/\1>', one_line)

        full_case_text = prefix + one_line
        seg_tag = f"<!-- === SEGMENT: {sub} | {sec_title} === -->"
        output_parts.append(f"{seg_tag}\n\n{full_case_text}")

    # 3. APPENDIX
    output_parts.append(
        "<!-- === SEGMENT: APPENDIX | Огляд судової практики Верховного Суду щодо затримання особи. Вихідні дані. Технічний сегмент. Не підлягає розподілу === -->\n\n"
        + APPENDIX_TEXT
    )

    final_text = "\n\n".join(output_parts) + "\n"

    # Запис у вихідний файл
    with open(SRC_PATH, 'w', encoding='utf-8', errors='surrogateescape', newline='') as f:
        f.write(final_text)

    print(f"✅ Успішно записано {len(output_parts)} сегментів (1 преамбула + 37 правових позицій + 1 апендікс) у {SRC_PATH}")


if __name__ == '__main__':
    main()
