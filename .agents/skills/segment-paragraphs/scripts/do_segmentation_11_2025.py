def build_segmented_text(file_path: str) -> str:
    with open(file_path, 'r', encoding='utf-8', errors='surrogateescape') as f:
        raw = f.read()

    cleaned = re.sub(r'\n\d+\s*\nОгляд судової практики ККС ВС\s*\n', '\n', raw)

    abbrev_match = re.search(r'ЦК\s+Цивільний\s+кодекс\s+України', cleaned)
    if not abbrev_match:
        raise ValueError("Не знайдено закінчення переліку скорочень (ЦК)")
    preamble_text = cleaned[:abbrev_match.end()].strip()

    app_match = re.search(r'Огляд судової практики Касаційного кримінального суду у складі Верховного Суду\s*\n\(актуальна практика\)', cleaned)
    if not app_match:
        raise ValueError("Не знайдено застереження/вихідних даних")
    appendix_text = cleaned[app_match.start():].strip()

    dec_blocks = {}
    for d in DECISIONS:
        m = re.search(d['anchor_regex'], cleaned)
        if not m:
            raise ValueError(f"Не знайдено anchor для сегмента {d['num']}")
        cit_m = re.search(r'<https?://reyestr\.court\.gov\.ua/Review/' + d['end_url'] + r'>', cleaned[m.start():])
        if not cit_m:
            raise ValueError(f"Не знайдено citation url для сегмента {d['num']}")
        chunk_raw = cleaned[m.start() : m.start() + cit_m.end()]
        chunk_raw = re.sub(d['strip_num_regex'], '', chunk_raw, count=1)
        chunk_lines = [l.strip() for l in chunk_raw.splitlines() if l.strip()]
        merged_body = ' '.join(chunk_lines)
        full_seg = d['prefix'] + ' ' + merged_body
        full_seg = re.sub(r'\s+', ' ', full_seg).strip()
        dec_blocks[d['num']] = (d['tag'], full_seg)

    out_parts = []

    # 1. Preamble
    out_parts.append('<!-- === SEGMENT: PREAMBLE | Огляд судової практики ККС ВС. ЗМІСТ. Перелік скорочень. Технічний сегмент. Не підлягає розподілу === -->\n\n' + preamble_text)

    # 2. Section I
    out_parts.append('<!-- === SEGMENT: РОЗДІЛ I | РОЗДІЛ I. СУДОВІ РІШЕННЯ ПАЛАТИ КАСАЦІЙНОГО КРИМІНАЛЬНОГО СУДУ У СКЛАДІ ВЕРХОВНОГО СУДУ, ЯКІ МІСТЯТЬ ВИСНОВКИ ЩОДО ЗАСТОСУВАННЯ НОРМИ ПРАВА У ПОДІБНИХ ПРАВОВІДНОСИНАХ. Технічний сегмент. Не підлягає розподілу === -->\n\n' + 'РОЗДІЛ I. СУДОВІ РІШЕННЯ ПАЛАТИ КАСАЦІЙНОГО КРИМІНАЛЬНОГО СУДУ У СКЛАДІ ВЕРХОВНОГО СУДУ, ЯКІ МІСТЯТЬ ВИСНОВКИ ЩОДО ЗАСТОСУВАННЯ НОРМИ ПРАВА У ПОДІБНИХ ПРАВОВІДНОСИНАХ.')
    out_parts.append(dec_blocks[1][0] + '\n\n' + dec_blocks[1][1])

    # 3. Section II
    out_parts.append('<!-- === SEGMENT: РОЗДІЛ II | РОЗДІЛ II. КРИМІНАЛЬНІ ПРОВАДЖЕННЯ, ПЕРЕДАНІ НА РОЗГЛЯД ВЕЛИКОЇ ПАЛАТИ ВЕРХОВНОГО СУДУ, ОБ’ЄДНАНОЇ ПАЛАТИ ТА СУДОВОЇ ПАЛАТИ КАСАЦІЙНОГО КРИМІНАЛЬНОГО СУДУ У СКЛАДІ ВЕРХОВНОГО СУДУ. Технічний сегмент. Не підлягає розподілу === -->\n\n' + 'РОЗДІЛ II Кримінальні провадження, передані на розгляд Великої Палати Верховного Суду, Об’єднаної палати та судової палати Касаційного кримінального суду у складі Верховного Суду.')
    for i in range(2, 7):
        out_parts.append(dec_blocks[i][0] + '\n\n' + dec_blocks[i][1])

    # 4. Section III
    out_parts.append('<!-- === SEGMENT: РОЗДІЛ III | РОЗДІЛ III. ЗАСТОСУВАННЯ НОРМ КРИМІНАЛЬНОГО ПРАВА УКРАЇНИ. Технічний сегмент. Не підлягає розподілу === -->\n\n' + 'РОЗДІЛ III. ЗАСТОСУВАННЯ НОРМ КРИМІНАЛЬНОГО ПРАВА УКРАЇНИ.')
    out_parts.append('<!-- === SEGMENT: I. ЗАСТОСУВАННЯ НОРМ ЗАГАЛЬНОЇ ЧАСТИНИ КРИМІНАЛЬНОГО ПРАВА УКРАЇНИ | I. ЗАСТОСУВАННЯ НОРМ ЗАГАЛЬНОЇ ЧАСТИНИ КРИМІНАЛЬНОГО ПРАВА УКРАЇНИ. Технічний сегмент. Не підлягає розподілу === -->\n\n' + 'I. ЗАСТОСУВАННЯ НОРМ ЗАГАЛЬНОЇ ЧАСТИНИ КРИМІНАЛЬНОГО ПРАВА УКРАЇНИ.')
    for i in range(7, 10):
        out_parts.append(dec_blocks[i][0] + '\n\n' + dec_blocks[i][1])

    out_parts.append('<!-- === SEGMENT: II. ЗАСТОСУВАННЯ НОРМ ОСОБЛИВОЇ ЧАСТИНИ КРИМІНАЛЬНОГО ПРАВА УКРАЇНИ | II. ЗАСТОСУВАННЯ НОРМ ОСОБЛИВОЇ ЧАСТИНИ КРИМІНАЛЬНОГО ПРАВА УКРАЇНИ. Технічний сегмент. Не підлягає розподілу === -->\n\n' + 'II. ЗАСТОСУВАННЯ НОРМ ОСОБЛИВОЇ ЧАСТИНИ КРИМІНАЛЬНОГО ПРАВА УКРАЇНИ.')
    for i in range(10, 19):
        out_parts.append(dec_blocks[i][0] + '\n\n' + dec_blocks[i][1])

    # 5. Section IV
    out_parts.append('<!-- === SEGMENT: РОЗДІЛ IV | РОЗДІЛ IV. ЗАСТОСУВАННЯ НОРМ КРИМІНАЛЬНОГО ПРОЦЕСУАЛЬНОГО ПРАВА УКРАЇНИ. Технічний сегмент. Не підлягає розподілу === -->\n\n' + 'РОЗДІЛ IV. ЗАСТОСУВАННЯ НОРМ КРИМІНАЛЬНОГО ПРОЦЕСУАЛЬНОГО ПРАВА УКРАЇНИ.')
    out_parts.append('<!-- === SEGMENT: I. ЗАГАЛЬНІ ПОЛОЖЕННЯ | I. ЗАГАЛЬНІ ПОЛОЖЕННЯ. Технічний сегмент. Не підлягає розподілу === -->\n\n' + 'I. ЗАГАЛЬНІ ПОЛОЖЕННЯ')
    out_parts.append(dec_blocks[19][0] + '\n\n' + dec_blocks[19][1])
    out_parts.append(dec_blocks[20][0] + '\n\n' + dec_blocks[20][1])
    out_parts.append(dec_blocks[21][0] + '\n\n' + dec_blocks[21][1])
    out_parts.append(dec_blocks[22][0] + '\n\n' + dec_blocks[22][1])
    out_parts.append(dec_blocks[23][0] + '\n\n' + dec_blocks[23][1])

    out_parts.append('<!-- === SEGMENT: II. ДОСУДОВЕ РОЗСЛІДУВАННЯ | II. ДОСУДОВЕ РОЗСЛІДУВАННЯ. Технічний сегмент. Не підлягає розподілу === -->\n\n' + 'II. ДОСУДОВЕ РОЗСЛІДУВАННЯ')
    for i in range(24, 32):
        out_parts.append(dec_blocks[i][0] + '\n\n' + dec_blocks[i][1])

    out_parts.append('<!-- === SEGMENT: III. СУДОВЕ ПРОВАДЖЕННЯ У ПЕРШІЙ ІНСТАНЦІЇ | III. СУДОВЕ ПРОВАДЖЕННЯ У ПЕРШІЙ ІНСТАНЦІЇ. Технічний сегмент. Не підлягає розподілу === -->\n\n' + 'III. СУДОВЕ ПРОВАДЖЕННЯ У ПЕРШІЙ ІНСТАНЦІЇ')
    out_parts.append(dec_blocks[32][0] + '\n\n' + dec_blocks[32][1])
    out_parts.append(dec_blocks[33][0] + '\n\n' + dec_blocks[33][1])

    out_parts.append('<!-- === SEGMENT: IV. СУДОВЕ ПРОВАДЖЕННЯ З ПЕРЕГЛЯДУ СУДОВИХ РІШЕНЬ | IV. СУДОВЕ ПРОВАДЖЕННЯ З ПЕРЕГЛЯДУ СУДОВИХ РІШЕНЬ. Технічний сегмент. Не підлягає розподілу === -->\n\n' + 'IV. СУДОВЕ ПРОВАДЖЕННЯ З ПЕРЕГЛЯДУ СУДОВИХ РІШЕНЬ')
    out_parts.append(dec_blocks[34][0] + '\n\n' + dec_blocks[34][1])
    out_parts.append(dec_blocks[35][0] + '\n\n' + dec_blocks[35][1])

    out_parts.append('<!-- === SEGMENT: V. ВИКОНАННЯ СУДОВИХ РІШЕНЬ | V. ВИКОНАННЯ СУДОВИХ РІШЕНЬ. Технічний сегмент. Не підлягає розподілу === -->\n\n' + 'V. ВИКОНАННЯ СУДОВИХ РІШЕНЬ')
    out_parts.append(dec_blocks[36][0] + '\n\n' + dec_blocks[36][1])

    # 6. Appendix
    out_parts.append('<!-- === SEGMENT: APPENDIX | Огляд судової практики ККС ВС. Вихідні дані. Застереження. Технічний сегмент. Не підлягає розподілу === -->\n\n' + appendix_text)

    return '\n\n'.join(out_parts) + '\n'


