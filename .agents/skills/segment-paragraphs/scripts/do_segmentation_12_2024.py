def normalize_text_block(raw_text: str) -> str:
    """Зливає багаторядковий текст позиції в один суцільний рядок."""
    # Заміна переносу на дефісі при розриві рядка (напр. 23-\nк -> 23-к)
    cleaned = re.sub(r'(\S+)-\n(\S+)', r'\1-\2', raw_text)
    # Звичайні розриви рядків замінюємо на пробіли
    lines = cleaned.splitlines()
    words = []
    for line in lines:
        stripped = line.strip()
        if stripped:
            words.append(stripped)
    one_line = " ".join(words)
    # Нормалізація подвійних пробілів у місцях злиття
    one_line = re.sub(r' +', ' ', one_line)
    # Очищення та приведення URL реєстру до єдиного формату <https://reyestr.court.gov.ua/Review/...>
    one_line = re.sub(r'<https://reyestr\.court\.gov\.ua/Review/(\d+)>', r'https://reyestr.court.gov.ua/Review/\1', one_line)
    one_line = re.sub(r'https://reyestr\.court\.gov\.ua/Review/(\d+)', r'<https://reyestr.court.gov.ua/Review/\1>', one_line)
    return one_line

