def clean_page_headers(text):
    text = re.sub(r'\n\s*\d+\s*\n\s*Огляд судової практики ККС ВС\s*\n', '\n', text)
    text = re.sub(r'^\s*\d+\s*\n\s*Огляд судової практики ККС ВС\s*\n', '', text)
    text = re.sub(r'\n\s*\d+\s*\n\s*Огляд судової практики ККС ВС\s*$', '', text)
    return text

def flatten_to_single_line(text):
    lines = [l.strip() for l in text.split('\n') if l.strip()]
    res = ' '.join(lines)
    res = re.sub(r'[ \t]+', ' ', res).strip()
    return res

