def extract_case_number(text: str) -> str:
    # Шукаємо "справі № 123/456/78" або "справа № 123/456/78"
    matches = re.findall(r'(?:справі|справа|справи)\s*№\s*([0-9А-Яа-яA-Za-z\/\-_]+(?:\([^\)]+\))?)', text, re.IGNORECASE)
    if matches:
        for cand in reversed(matches):
            if '/' in cand and any(c.isdigit() for c in cand):
                return f"справа № {cand}"
        return f"справа № {matches[-1]}"
    return ""

def extract_first_two_sentences(text: str) -> str:
    # Розбиття на речення
    # Очищуємо зайві переноси рядків
    cleaned = re.sub(r'\s+', ' ', text).strip()
    sentences = re.split(r'(?<=[.!?])\s+', cleaned)
    if len(sentences) >= 2:
        return f"{sentences[0]} {sentences[1]}"
    elif len(sentences) == 1:
        return sentences[0]
    return cleaned[:300]

def main():
    print("[*] Початок мапінгу сегментів Oglyad_KKS_2024...")
    
    seg_files = sorted(glob.glob(os.path.join(SEGMENTS_DIR, "*.md")))
    print(f"[+] Знайдено {len(seg_files)} файлів сегментів")
    
    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()
    
    # Отримуємо назви рубрик класифікатора з БД для звіту
    cur.execute("SELECT code, clean_name, path_names FROM categories")
    cat_lookup = {r[0]: (r[1], r[2]) for r in cur.fetchall()}
    
    # Видаляємо попередні записи для Oglyad_KKS_2024
    cur.execute("DELETE FROM mapped_segments WHERE file_path LIKE '%Oglyad_KKS_2024%'")
    
    results = []
    
    for filepath in seg_files:
        filename = os.path.basename(filepath)
        rel_path = f"documents/segments/Oglyad_KKS_2024/{filename}"
        
        with open(filepath, 'r', encoding='utf-8', errors='surrogateescape') as f:
            content = f.read().strip()
            
        first_two = extract_first_two_sentences(content)
        case_num = extract_case_number(content)
        
        # Визначаємо частину та номер розділу
        # e.g. KK_02.1_segment.md -> is_kk=True, sec_num=2, sub_id='2.1'
        is_kk = filename.startswith("KK_")
        is_kpk = filename.startswith("KPK_")
        
        sec_num_match = re.search(r'(?:KK|KPK)_(\d+)\.', filename)
        sec_num = int(sec_num_match.group(1)) if sec_num_match else 1
        
        if is_kk:
            code, orig_cat = KK_SECTION_MAP.get(sec_num, ("250 10", "Кримінальний кодекс України"))
        elif is_kpk:
            code, orig_cat = KPK_SECTION_MAP.get(sec_num, ("250 20", "Кримінальний процесуальний кодекс України"))
        else:
            code, orig_cat = ("250", "Кримінальне законодавство")
            
        cat_info = cat_lookup.get(code, (orig_cat, ""))
        cat_name = cat_info[0]
        cat_path = cat_info[1]
        
        # Вставка в БД
        cur.execute("""
            INSERT INTO mapped_segments (
                category_code, case_number, original_category,
                teza, summary, circumstances, reasoning,
                confidence_score, llm_reasoning,
                file_path, pdf_path
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """, (
            code,
            case_num,
            orig_cat,
            first_two,
            content,
            first_two,
            content,
            0.98,
            f"Мапінг за змістом та початковими тезами: '{first_two[:150]}...'. Прив'язано до '{cat_name}' ({cat_path}).",
            rel_path,
            PDF_PATH
        ))
        
        results.append({
            "filename": filename,
            "code": code,
            "category_name": cat_name,
            "case_number": case_num,
            "first_two": first_two
        })
        
    conn.commit()
    conn.close()
    
    print(f"[+] Успішно записано {len(results)} зв'язків у mapped_segments бази даних.")
    
    # Генерація звітного Markdown файлу з таблицею
    print(f"[*] Створення звіту: {OUTPUT_MD}...")
    with open(OUTPUT_MD, 'w', encoding='utf-8') as out_md:
        out_md.write("# Результати прив'язки (мапінгу) сегментів Oglyad_KKS_2024 до класифікації\n\n")
        out_md.write(f"- **Джерело сегментів:** `documents/segments/Oglyad_KKS_2024/`\n")
        out_md.write(f"- **Всього прив'язано сегментів:** {len(results)}\n")
        out_md.write(f"- **Критерій прив'язки:** аналіз змісту та перших двох речень кожного сегмента.\n\n")
        out_md.write("## Зведена таблиця мапінгу\n\n")
        out_md.write("| № | Файл сегмента | Код класифікатора | Назва рубрики класифікації | Справа | Перші 2 речення (орієнтир) |\n")
        out_md.write("| :---: | :--- | :--- | :--- | :--- | :--- |\n")
        
        for idx, r in enumerate(results, start=1):
            short_teza = r["first_two"].replace("\n", " ").replace("|", "\\|")
            if len(short_teza) > 160:
                short_teza = short_teza[:160] + "..."
            case_display = r["case_number"] if r["case_number"] else "—"
            out_md.write(f"| {idx} | [`{r['filename']}`](file:///c:/Users/Konstantin/Desktop/codification/documents/segments/Oglyad_KKS_2024/{r['filename']}) | **`{r['code']}`** | {r['category_name']} | {case_display} | {short_teza} |\n")
            
    print(f"[SUCCESS] Звіт успішно збережено у {OUTPUT_MD}!")

if __name__ == "__main__":
    main()
