def clean_chunk(raw_chunk: str) -> str:
    # Handle hyphenated linebreaks like "суспільно -\nнебезпечних" -> "суспільно-небезпечних"
    chunk = re.sub(r'(\w+)\s*-\s*\n\s*(\w+)', r'\1-\2', raw_chunk)
    lines = [l.strip() for l in chunk.splitlines() if l.strip()]
    merged = ' '.join(lines)
    merged = re.sub(r' {2,}', ' ', merged)
    return merged.strip()


