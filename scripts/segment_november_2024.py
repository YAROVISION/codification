    matches3 = list(re.finditer(r'<https?://reyestr\.court\.gov\.ua/Review/(\d+)>', sec3_text))
    p3 = 0
    for idx, m in enumerate(matches3):
        chunk = sec3_text[p3:m.end()]
        p3 = m.end()

        # Insert Subsection II tech segment before Chapter 5 (idx == 4)
        if idx == 4:
            sec3_sub2_tech = (
                "<!-- === SEGMENT: II. ДОСУДОВЕ РОЗСЛІДУВАННЯ | II. ДОСУДОВЕ РОЗСЛІДУВАННЯ. Технічний сегмент. Не підлягає розподілу === -->\n\n"
                "II. ДОСУДОВЕ РОЗСЛІДУВАННЯ\n"
            )
            segments_output.append(sec3_sub2_tech)

        # Insert Subsection III tech segment before Chapter 10 (idx == 9)
        if idx == 9:
            sec3_sub3_tech = (
                "<!-- === SEGMENT: III. СУДОВЕ ПРОВАДЖЕННЯ У ПЕРШІЙ ІНСТАНЦІЇ | III. СУДОВЕ ПРОВАДЖЕННЯ У ПЕРШІЙ ІНСТАНЦІЇ. Технічний сегмент. Не підлягає розподілу === -->\n\n"
                "III. СУДОВЕ ПРОВАДЖЕННЯ У ПЕРШІЙ ІНСТАНЦІЇ\n"
            )
            segments_output.append(sec3_sub3_tech)

        tag_num, tag_title, prefix = sec3_meta[idx]

        cleaned_lines = []
        for l in chunk.splitlines():
            ls = l.strip()
            if not ls:
                continue
            if ls.startswith('РОЗДІЛ III') or ls.startswith('I. ЗАГАЛЬНІ') or ls.startswith('II. ДОСУДОВЕ') or ls.startswith('III. СУДОВЕ'):
                continue
            if re.match(r'^\d+\.\s+(?:Засади|Поняття|Сторона|Відшкодування|Слідчі|Негласні|Закінчення|Звернення|Оскарження|Підготовче|Загальні)', ls):
                continue
            if re.match(r'^\d+\.\d+\.\s+(?:Мова|Докази|Відмова|Відшкодування|Проникнення|Загальні|Закриття|Відкриття|Рішення|Вирішення|Зупинення)', ls):
                continue
            cleaned_lines.append(ls)

        body_str = clean_chunk(' '.join(cleaned_lines))
        body_str = re.sub(r'^\d+\.\d+\.\d+\.\s*', '', body_str)
        merged = prefix + body_str
        tag = f"<!-- === SEGMENT: {tag_num} | {tag_title} === -->"
        segments_output.append(f"{tag}\n\n{merged}\n")

    # ==========================
    # --- APPENDIX ---
    # ==========================
    raw_appendix = clean_text[outro_pos:].strip()
    appendix_segment = (
        "<!-- === SEGMENT: APPENDIX | Огляд судової практики ККС ВС за листопад 2024 року. Застереження. Інформаційні матеріали. Технічний сегмент. Не підлягає розподілу === -->\n\n"
        + raw_appendix
        + "\n"
    )
    segments_output.append(appendix_segment)

    return "\n".join(segments_output)


