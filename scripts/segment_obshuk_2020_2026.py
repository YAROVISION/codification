def clean_decision_body(chunk: str) -> str:
    lines = [l.strip() for l in chunk.splitlines() if l.strip()]
    while lines:
        cleaned_first = lines[0].strip(' .–-\t')
        if not cleaned_first:
            lines.pop(0)
            continue
        matched = False
        for h in HEADERS_TO_STRIP:
            if cleaned_first == h or cleaned_first.startswith(h):
                lines.pop(0)
                matched = True
                break
        if not matched:
            break

    merged = ' '.join(lines)
    merged = re.sub(r' {2,}', ' ', merged).strip(' .–-\t')
    return merged


