def clean_chunk(raw_chunk: str) -> str:
    lines = [l.strip() for l in raw_chunk.splitlines() if l.strip()]
    merged = ' '.join(lines)
    merged = re.sub(r' {2,}', ' ', merged)
    return merged.strip()


