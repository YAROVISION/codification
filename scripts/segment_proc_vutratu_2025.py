def clean_block(raw: str) -> str:
    lines = [l.strip() for l in raw.splitlines() if l.strip()]
    while lines:
        cleaned = lines[0].strip(' .–-\t')
        matched = False
        for h in HEADERS_TO_STRIP:
            if cleaned == h or cleaned.startswith(h):
                lines.pop(0)
                matched = True
                break
        if not matched:
            break
    merged = ' '.join(lines)
    merged = re.sub(r' {2,}', ' ', merged).strip()
    return merged


