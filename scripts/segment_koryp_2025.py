def clean_footers(text: str) -> str:
    # Remove PDF headers: page number + header line
    return re.sub(r'\n+\d+\s*\n+Огляд судової практики ККС ВС\s*\n+', '\n\n', text)

def normalize_line(line_text: str) -> str:
    lines = [l.strip() for l in line_text.splitlines() if l.strip()]
    merged = ' '.join(lines)
    merged = re.sub(r'\s+', ' ', merged)
    # Ensure URL format: <https://...>
    merged = re.sub(r'URL:\s*<*(https://reyestr\.court\.gov\.ua/Review/\d+)>*', r'<\1>', merged)
    # Remove period before <https... if right after closing bracket
    merged = re.sub(r'(\))\.\s*<(https://reyestr\.court\.gov\.ua/Review/\d+)>', r'\1 <\2>', merged)
    return merged.strip()

def extract_positions(block_text: str, prefix: str):
    """
    Splits a block of text into distinct court decision positions.
    Each position ends with a court decision reference (and optional 'Аналогічна позиція').
    """
    # Decision pattern: Постанова ... https://reyestr.court.gov.ua/Review/...
    # Note: 'Аналогічна позиція — у постанові ...' should be glued to the preceding decision.
    rev_pat = re.compile(r'(?:Постанова\s+(?:колегії\s+суддів\s+[^\n]+\s+)?(?:ОП\s+)?ККС\s+ВС[^\n]*\n?(?:[^\n]*\n?)?.*?https://reyestr\.court\.gov\.ua/Review/\d+>?)')
    
    # We find all matches of rev_pat or review URLs
    url_pat = re.compile(r'https://reyestr\.court\.gov\.ua/Review/\d+>?')
    urls = list(url_pat.finditer(block_text))
    if not urls:
        return []
    
    # Group decisions: if 'Аналогічна позиція' precedes the next url, attach it to previous
    slices = []
    i = 0
    while i < len(urls):
        curr_url = urls[i]
        curr_end = curr_url.end()
        # Check if right after curr_end there is 'Аналогічна позиція' leading to next url
        if i + 1 < len(urls):
            between = block_text[curr_end:urls[i+1].start()]
            if 'Аналогічна позиція' in between:
                # Merge with next
                curr_end = urls[i+1].end()
                i += 1
        slices.append(curr_end)
        i += 1
    
    positions = []
    prev_pos = 0
    for s_end in slices:
        raw_slice = block_text[prev_pos:s_end].strip()
        prev_pos = s_end
        
        # Merge into single line with prefix
        full_text = f"{prefix}{raw_slice}"
        norm = normalize_line(full_text)
        positions.append(norm)
        
    return positions

