def add_categories_to_sqlite():
    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()
    
    print(f"Додавання {len(CATEGORIES)} категорій до {DB_PATH}...")
    for code, name, clean_name, parent, level, path_n, path_c, has_ch, ch_cnt in CATEGORIES:
        semantic = f"{name} {clean_name}"
        cur.execute("""
            INSERT OR REPLACE INTO categories (
                code, name, clean_name, parent_code, level, path_names, path_codes, 
                has_children, children_count, semantic_text, total_docs_count, direct_docs_count
            )
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 0, 0)
        """, (code, name, clean_name, parent, level, path_n, path_c, has_ch, ch_cnt, semantic))
        
    conn.commit()
    conn.close()
    print("✅ Категорії успішно додано до SQLite.")


