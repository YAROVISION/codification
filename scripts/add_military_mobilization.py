def update_classifier_json():
    json_path = BASE_DIR / "data" / "classifier.json"
    with open(json_path, "r", encoding="utf-8") as f:
        tree = json.load(f)

    # Побудуємо вузли зі списку CATEGORIES
    nodes = {}
    for code, name, clean_name, parent, level, path_n, path_c, has_ch, ch_cnt in CATEGORIES:
        node = {
            "code": code,
            "level": level,
            "name": name,
            "clean_name": clean_name,
            "parent_code": parent if parent else "",
            "branch_url": "",
            "direct_url": "",
            "total_docs_count": 0,
            "direct_docs_count": 0,
            "cross_references": []
        }
        if has_ch:
            node["children"] = []
        nodes[code] = node

    # Зв'язуємо ієрархію
    for code, node in nodes.items():
        parent_code = node["parent_code"]
        if parent_code and parent_code in nodes:
            nodes[parent_code]["children"].append(node)

    root_node_210 = nodes["210"]

    # Видаляємо 210, якщо вже був у tree
    tree = [n for n in tree if n["code"] != "210"]
    tree.append(root_node_210)

    def sort_key(x):
        parts = [int(p) if p.isdigit() else 0 for p in x["code"].split()]
        return parts

    tree.sort(key=sort_key)

    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(tree, f, ensure_ascii=False, indent=2)

    print("✅ Додано категорію 210 та всю структуру до data/classifier.json")


