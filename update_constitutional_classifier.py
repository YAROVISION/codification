def update_database():
    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()

    print("[1/5] Оновлення кореневої категорії 10...")
    cur.execute("""
        UPDATE categories SET
            name = 'Конституційне право',
            clean_name = 'Конституційне право',
            path_names = 'Конституційне право',
            path_codes = '10',
            semantic_text = 'Конституційне право. Шлях: Конституційне право. Код: 10.',
            has_children = 1,
            children_count = 1
        WHERE code = '10'
    """)

    print("[2/5] Видалення старих підрозділів у категорії 10...")
    # Get all old codes under 10
    cur.execute("SELECT code FROM categories WHERE parent_code = '10' OR path_codes LIKE '10 / %'")
    old_sub_codes = [r[0] for r in cur.fetchall()]
    print(f"Знайдено {len(old_sub_codes)} застарілих підкатегорій для видалення.")

    # Re-point mapped_segments if any
    cur.execute("UPDATE mapped_segments SET category_code = '10' WHERE category_code IN ({seq})".format(
        seq=','.join(['?']*len(old_sub_codes))
    ), old_sub_codes)
    repointed = cur.rowcount
    if repointed > 0:
        print(f"Переприв'язано {repointed} сегментів на категорію 10.")

    # Delete from categories and categories_fts
    cur.execute("DELETE FROM categories WHERE parent_code = '10' OR path_codes LIKE '10 / %'")
    for code in old_sub_codes:
        cur.execute("DELETE FROM categories_fts WHERE code = ?", (code,))
    # Update category 10 in FTS
    cur.execute("DELETE FROM categories_fts WHERE code = '10'")
    cur.execute("""
        INSERT INTO categories_fts (code, clean_name, path_names, semantic_text)
        VALUES ('10', 'Конституційне право', 'Конституційне право', 'Конституційне право Конституційне право 10')
    """)

    print("[3/5] Створення розділу 'Конституція України' (код 10 10)...")
    cur.execute("""
        INSERT INTO categories (
            code, level, name, clean_name, parent_code,
            path_codes, path_names, cross_references,
            branch_url, direct_url, total_docs_count, direct_docs_count,
            has_children, children_count, semantic_text
        ) VALUES (
            '10 10', 2, 'Конституція України', 'Конституція України', '10',
            '10 / 10 10', 'Конституційне право / Конституція України', '[]',
            '', '', 0, 0, 1, ?, 'Конституція України. Шлях: Конституційне право / Конституція України. Код: 10 10.'
        )
    """, (len(CONSTITUTION_STRUCTURE),))

    cur.execute("""
        INSERT INTO categories_fts (code, clean_name, path_names, semantic_text)
        VALUES ('10 10', 'Конституція України', 'Конституційне право / Конституція України', 'Конституція України Конституційне право / Конституція України 10 10')
    """)

    print("[4/5] Додавання розділів та статей Конституції України...")
    total_articles = 0

    for ch in CONSTITUTION_STRUCTURE:
        ch_code = f"10 10 {ch['code_suffix']}"
        ch_name = ch["name"]
        ch_path_codes = f"10 / 10 10 / {ch_code}"
        ch_path_names = f"Конституційне право / Конституція України / {ch_name}"
        ch_semantic = f"{ch_name}. Шлях: {ch_path_names}. Код: {ch_code}."
